const PACKS = { en, ja, zh, km, ne, ta };

export function getLang() {
  const v = localStorage.getItem(KEY);
  return LANGS.some((l) => l.id === v) ? v : "ko";
}

export function setLang(id) {
  const next = LANGS.some((l) => l.id === id) ? id : "ko";
  localStorage.setItem(KEY, next);
  applyHtmlLang();
}

export function applyHtmlLang() {
  document.documentElement.lang = HTML[getLang()] || "ko";
}

export function t(text, vars) {
  if (text == null) return "";
  const lang = getLang();
  let s = String(text);
  if (lang !== "ko") s = PACKS[lang]?.[s] || PACKS.en?.[s] || s;
  if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replaceAll(`{${k}}`, String(v)); });
  return s;
}

export function langBar() {
  const cur = getLang();
  return `<label class="lang-pick"><span class="lang-pick-l">${t("언어")}</span>
    <select id="lang" aria-label="${t("언어")}">${LANGS.map((l) => `<option value="${l.id}" ${l.id === cur ? "selected" : ""}>${l.label}</option>`).join("")}</select></label>`;
}

export function bindLang(rerender) {
  document.getElementById("lang")?.addEventListener("change", (e) => {
    setLang(e.target.value);
    rerender();
  });
}
